#!/usr/bin/env python3
"""Export generalized accounting coverage; missing raw evidence stays unavailable."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "arc"))
from audit_marginal_literal_reuse import MarginalReuseRow, system_summary


def build_report(payload):
    summaries = {}
    rows = []
    for system in payload["summary"]["systems"]:
        source = [MarginalReuseRow(**row) for row in payload["rows"] if row["system"] == system]
        summaries[system] = system_summary(source)["source_reuse_accounting"]
        for row in source:
            if not row.exact_adjacent_transition:continue
            reuse = row.source_reuse or {}
            rows.append({"system": system, "game": row.game, "level": row.completed_level,
                         "M": row.marginal_ast_zlib_bytes, "sharp_drop": row.sharp_marginal_drop,
                         "status": reuse.get("status", "cached_direct_audit_only"),
                         "retained_targets": sorted(reuse.get("paths", {})),
                         "retained_entrypoint_targets": reuse.get("retained_entrypoint_targets", []),
                         "direct_targets": reuse.get("direct_targets", []),
                         "indirect_targets": reuse.get("indirect_targets", []),
                         "unresolved_sites": len(reuse.get("unresolved_calls", [])),
                         "observed_replay": bool(reuse.get("observed_replay_calls"))})
    return {"schema": 1, "method": "code-only source points-to analysis and separately bound replay observations",
            "summaries": summaries, "rows": rows,
            "scope": "Full source hashes and call paths are stored once in the joint audit. Cached comparator rows are not silently reclassified. No solver/harness grammar is imposed."}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audit", type=Path, default=ROOT / "arc/audit_results/marginal-literal-reuse.json")
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1] / "generated")
    args = parser.parse_args()
    raw = args.audit.read_bytes();report = build_report(json.loads(raw))
    report["joint_audit_sha256"] = hashlib.sha256(raw).hexdigest()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "reuse_accounting.json").write_text(json.dumps(report, indent=2) + "\n")
    lines = ["<!-- Generated by scripts/generate_reuse_accounting.py; do not edit. -->", "",
             "Generalized source-reuse accounting", "",
             "| System | Source pairs analysed | With retained path | Additional pairs via glue | Sharp drop + path | Bound replay observations |",
             "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for system, summary in report["summaries"].items():
        available = summary["exact_pairs_analysed"]
        values = [str(summary[name]) if available else "unavailable" for name in
                  ["pairs_with_retained_call_path", "pairs_with_only_indirect_paths", "sharp_drops_with_retained_call_path"]]
        lines.append(f"| {system} | {available} | {' | '.join(values)} | {summary['source_bound_replay_observations']} |")
    lines.extend(["", "Additional pairs via glue have retained paths but no direct target. Direct and indirect target sets can overlap at a boundary.",
                  "Unresolved source calls are explicit in the joint audit; replay observations record actual dispatch separately. Historical source-path counts are not replay-call counts.", ""])
    (args.output_dir / "reuse_accounting.md").write_text("\n".join(lines))
    gkm = report["summaries"]["GKM"]
    macros = {"GKMGeneralPairs": "exact_pairs_analysed", "GKMGeneralPaths": "pairs_with_retained_call_path",
              "GKMAdditionalGluePaths": "pairs_with_only_indirect_paths", "GKMGeneralSharpPaths": "sharp_drops_with_retained_call_path",
              "GKMGeneralUnresolved": "pairs_with_unresolved_sites"}
    tex = ["% Generated by scripts/generate_reuse_accounting.py; do not edit."]
    tex.extend("\\newcommand{\\" + name + "}{" + str(gkm[field]) + "}" for name, field in macros.items())
    (args.output_dir / "reuse_accounting.tex").write_text("\n".join(tex) + "\n")
    print(json.dumps(report["summaries"], sort_keys=True))


if __name__ == "__main__":
    main()
