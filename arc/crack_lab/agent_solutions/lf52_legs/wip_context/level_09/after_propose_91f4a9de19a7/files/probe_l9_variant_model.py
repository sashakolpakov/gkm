def main():
    start = int(os.environ.get("OPT_VARIANT_START", "0"))
    size = int(os.environ.get("OPT_VARIANT_SIZE", str(len(VARIANTS))))
    target = int(os.environ.get("OPT_TARGET_TOTAL", "102"))
    max_cost = int(os.environ.get("OPT_SCORE_COST", "74"))
    for index, (load_cost, bridges) in enumerate(
            VARIANTS[start:start + size], start):
        limit = min(max_cost, target - 1 - load_cost)
        path, states, _ = search(CELLS, FIXED, PEGS,
                                 frozenset(bridges), max_cost=limit)
        suffix = None if path is None else sum(
            1 if step[0] in (3, 4) else 2 for step in path
        )
        total = None if suffix is None else load_cost + suffix
        print("variant_score", index, load_cost, limit, suffix, total, states,
              path if total is not None else None, flush=True)


if __name__ == "__main__":
    main()
